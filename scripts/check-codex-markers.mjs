#!/usr/bin/env node
// ---------------------------------------------------------------------------
// check-codex-markers.mjs — every build-codex.mjs copy must claim EVERY marker
// generation that writes into $HOME/.codex.
//
// Two compilers write the same outputs: the legacy JS build-codex.mjs and the
// native `pfm codex build`. Each refuses to touch a file it does not recognize
// as generated (so it never clobbers hand-written work). That guard turns into
// silent drift the moment one compiler stops recognizing the other's marker:
// every file the other wrote reports STALE forever and no run can heal it.
//
// This gate reads the GENERATED_RE literal straight out of each script and runs
// it against a real header of each generation, plus a hand-written file that
// must still be rejected. Retire it with the JS compiler.
//
// usage: node scripts/check-codex-markers.mjs [file...]   (defaults to both copies)
// ---------------------------------------------------------------------------
import { readFileSync } from 'node:fs';

const FILES = process.argv.slice(2).length
  ? process.argv.slice(2)
  : ['.claude/scripts/build-codex.mjs', 'blueprint/scripts/build-codex.mjs'];

// Each generation's real first-line header, as written on disk today.
const CLAIMED = {
  'pfm codex build': '# Generated by pfm codex build from $HOME/.claude/commands/chat/inject.md; do not edit',
  'legacy build-codex.mjs':
    '# Generated by .claude/scripts/build-codex.mjs from .claude/commands/pcm.md; do not edit',
  'pre-blueprint infra': '# Generated from .professor/infra/codex/prompts/pcm.md; do not edit',
};
const REJECTED = '# A hand-written skill nobody generated. Do not delete me.';

let failed = 0;
const fail = (msg) => {
  console.error(`FAIL ${msg}`);
  failed++;
};

for (const file of FILES) {
  let literal;
  try {
    literal = readFileSync(file, 'utf8').match(/^const GENERATED_RE = \/(.+)\/;$/m)?.[1];
  } catch (e) {
    fail(`${file} — unreadable (${e.code})`);
    continue;
  }
  if (!literal) {
    fail(`${file} — no single-line \`const GENERATED_RE = /.../;\` found`);
    continue;
  }

  const re = new RegExp(literal);
  for (const [generation, header] of Object.entries(CLAIMED)) {
    if (!re.test(header)) fail(`${file} — does not claim "${generation}" output; it would strand as STALE`);
  }
  if (re.test(REJECTED)) fail(`${file} — claims an UNMARKED file; the clobber guard is gone`);
}

if (failed) {
  console.error(`codex marker claim FAILED — ${failed} problem(s) across ${FILES.length} file(s)`);
  process.exit(1);
}
console.log(
  `codex marker claim OK — ${FILES.length} compiler copy/copies claim all ${Object.keys(CLAIMED).length} generations and still reject unmarked files`,
);
